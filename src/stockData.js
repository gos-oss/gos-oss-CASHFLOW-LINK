export function normalizarNombreProyecto(p) {
  if (!p) return "Proyecto Link";
  const clean = String(p).trim();
  const lower = clean.toLowerCase();
  if (lower.includes("duo")) return "+ DUO Proyecto";
  if (lower.includes("green")) return "Torre Green Proyecto";
  if (lower.includes("auria")) return "Auria Proyecto";
  if (lower.includes("boulevard")) return "Cupo Link Boulevard";
  if (lower.includes("torre 4")) return "Cupo Link # 300 - Torre 4";
  if (lower.includes("torre 3")) return "Cupo Link # 300 - Torre 3";
  if (lower.includes("torre 2")) return "Cupo Link # 300 - Torre 2";
  if (lower.includes("corporativ")) return "Torre Corporativa";
  return clean;
}

